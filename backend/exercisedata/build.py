"""Validate data/exercises.csv and write a review report.

    uv run python -m exercisedata.build

Writes:
  data/exercises_validated.csv        rows with no errors, ready for loading (Step 5.3)
  data/reports/exercises_review.md    every exercise with its injury tags and flags, for a human to check

Statuses:  ready    = all checks passed AND a human signed off (reviewed_by is filled)
           review   = no errors, but a warning or the sign-off is still open
           blocked  = an error; NOT written to exercises_validated.csv
"""

import csv
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

from exercisedata.checks import check_exercise, check_library
from exercisedata.freedb import default_path, read_free_exercise_db
from exercisedata.records import COLUMNS, Exercise, read_exercises
from fooddata.checks import Issue
from fooddata.download import DATA_DIR

EXERCISES = DATA_DIR / "exercises.csv"
VALIDATED = DATA_DIR / "exercises_validated.csv"
REPORT = DATA_DIR / "reports" / "exercises_review.md"

MAJOR_MUSCLES = ("chest", "back", "shoulders", "biceps", "triceps", "abs", "glutes", "quads", "hamstrings", "calves")


@dataclass
class Reviewed:
    exercise: Exercise
    issues: list[Issue] = field(default_factory=list)

    @property
    def status(self) -> str:
        if any(i.severity == "error" for i in self.issues):
            return "blocked"
        if any(i.severity == "warning" for i in self.issues) or not self.exercise.reviewed_by:
            return "review"
        return "ready"


def review_all(exercises: list[Exercise], refs: dict) -> list[Reviewed]:
    reviewed = [Reviewed(ex, check_exercise(ex, refs.get(ex.ref_id))) for ex in exercises]
    library_issues = check_library(exercises)  # duplicates: attach to every row that shares the key or name
    for r in reviewed:
        r.issues += [i for i in library_issues if repr(r.exercise.key) in i.message or repr(r.exercise.name.lower()) in i.message]
    return reviewed


def coverage_notes(exercises: list[Exercise]) -> list[str]:
    """Gaps in the library as a whole: a user with no equipment or one body area must still get a plan."""
    notes = []
    patterns = Counter(e.movement_pattern for e in exercises)
    for pattern in ("squat", "hinge", "lunge", "push_horizontal", "push_vertical", "pull_horizontal", "pull_vertical", "core"):
        if patterns[pattern] < 3:
            notes.append(f"only {patterns[pattern]} '{pattern}' exercises (want at least 3)")
    bodyweight = [e for e in exercises if not e.equipment]
    main = Counter(e.muscle_groups[0] for e in bodyweight if e.muscle_groups)
    for muscle in MAJOR_MUSCLES:
        if main[muscle] < 1:
            notes.append(f"no bodyweight-only exercise for {muscle}: a user with no equipment has nothing for it")
    beginners = sum(e.difficulty == "beginner" for e in exercises)
    if exercises and beginners / len(exercises) < 0.3:
        notes.append(f"only {beginners} of {len(exercises)} are beginner level (want at least 30%)")
    for injury in ("shoulder", "knee", "lower_back", "wrist", "elbow", "neck", "hip", "ankle"):
        safe = [e for e in exercises if injury not in e.contraindications and e.movement_pattern not in ("mobility",)]
        if len(safe) < 25:
            notes.append(f"a user with a {injury} issue would have only {len(safe)} exercises left (want at least 25)")
    return notes


def write_validated(reviewed: list[Reviewed]) -> int:
    rows = [r for r in reviewed if r.status != "blocked"]
    with VALIDATED.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow([*COLUMNS, "status"])
        for r in rows:
            e = r.exercise
            writer.writerow([e.key, e.name, ";".join(e.muscle_groups), ";".join(e.equipment), e.location, e.difficulty,
                             e.movement_pattern, " | ".join(e.cues), ";".join(e.contraindications), e.ref_id,
                             e.reviewed_by, e.note, r.status])
    return len(rows)


def write_report(reviewed: list[Reviewed], notes: list[str]) -> None:
    counts = Counter(r.status for r in reviewed)
    lines = ["# Exercise library review", "",
             "Generated by `uv run python -m exercisedata.build`. **Injury tags are ours, not from any dataset: please read them.**", "",
             f"{len(reviewed)} exercises: " + ", ".join(f"{counts[s]} {s}" for s in ("ready", "review", "blocked")), "",
             "To sign off an exercise, fill `reviewed_by` in `data/exercises.csv` and re-run the build.", ""]
    lines += ["## Gaps in the library as a whole", ""] + ([f"- {n}" for n in notes] or ["- none"]) + [""]
    unchecked = [r.exercise.key for r in reviewed if not r.exercise.ref_id]
    lines += ["## Not cross-checked (no Free Exercise DB entry cited)", "",
              f"{len(unchecked)} of {len(reviewed)}: " + (", ".join(unchecked) or "none"), ""]
    problems = [r for r in reviewed if r.issues]
    lines += ["## Flags", ""]
    for r in problems:
        for i in r.issues:
            lines.append(f"- **{r.exercise.key}** ({i.severity}, {i.check}): {i.message}")
    if not problems:
        lines.append("- none")
    lines += ["", "## Every exercise", "",
              "| status | key | name | pattern | level | place | equipment | injury tags | ref |", "|---|---|---|---|---|---|---|---|---|"]
    for r in reviewed:
        e = r.exercise
        lines.append(f"| {r.status} | {e.key} | {e.name} | {e.movement_pattern} | {e.difficulty} | {e.location} | "
                     f"{', '.join(e.equipment) or '-'} | {', '.join(e.contraindications) or '-'} | {e.ref_id or '-'} |")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    exercises = read_exercises(EXERCISES)
    refs = {r.id: r for r in read_free_exercise_db(default_path())}
    reviewed = review_all(exercises, refs)
    notes = coverage_notes(exercises)
    written = write_validated(reviewed)
    write_report(reviewed, notes)
    counts = Counter(r.status for r in reviewed)
    print(f"{len(reviewed)} exercises: " + ", ".join(f"{counts[s]} {s}" for s in ("ready", "review", "blocked")))
    print(f"wrote {written} rows to {VALIDATED.name} and the report {REPORT.name}; {len(notes)} library gap(s)")
    for r in reviewed:
        for i in r.issues:
            if i.severity == "error":
                print(f"  ERROR {r.exercise.key}: {i.message}")
    return 1 if counts["blocked"] else 0


if __name__ == "__main__":
    sys.exit(main())
